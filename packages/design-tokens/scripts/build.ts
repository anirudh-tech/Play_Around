import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { blur, palette, radii, semantic, sportAccents, typography } from '../src/index.ts';

const distDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'dist');
const header = '/* Generated by packages/design-tokens/scripts/build.ts. Do not edit. */';
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

// Tailwind v4 theme for web and admin.
function buildThemeCss(): string {
  const lines = [header, '@theme {'];
  for (const [name, value] of Object.entries(palette)) {
    if (typeof value === 'string') lines.push(`  --color-${name}: ${value};`);
    else for (const [step, hex] of Object.entries(value)) lines.push(`  --color-${name}-${step}: ${hex};`);
  }
  for (const [sport, hex] of Object.entries(sportAccents)) lines.push(`  --color-sport-${sport}: ${hex};`);
  for (const key of Object.keys(semantic.light)) {
    lines.push(`  --color-${kebab(key)}: var(--pa-${kebab(key)});`);
  }
  for (const [name, px] of Object.entries(radii)) lines.push(`  --radius-${name}: ${px}px;`);
  for (const [name, px] of Object.entries(blur)) lines.push(`  --blur-glass-${name}: ${px}px;`);
  lines.push(`  --font-sans: ${typography.fontFamily.sans};`);
  lines.push(`  --font-display: ${typography.fontFamily.display};`);
  lines.push('}');

  const vars = (mode: keyof typeof semantic, indent: string) =>
    Object.entries(semantic[mode])
      .map(([key, value]) => `${indent}--pa-${kebab(key)}: ${value};`)
      .join('\n');

  lines.push(`:root {\n${vars('light', '  ')}\n}`);
  lines.push(`@media (prefers-color-scheme: dark) {\n  :root {\n${vars('dark', '    ')}\n  }\n}`);
  return `${lines.join('\n')}\n`;
}

// Tailwind v3 preset for NativeWind (mobile).
function buildNativewindPreset(): string {
  const colors = {
    ...palette,
    sport: sportAccents,
    surface: { light: semantic.light.surface, dark: semantic.dark.surface },
  };
  const borderRadius = Object.fromEntries(
    Object.entries(radii).map(([name, px]) => [name, `${px}px`]),
  );
  const preset = { theme: { extend: { colors, borderRadius } } };
  return `${header}\nmodule.exports = ${JSON.stringify(preset, null, 2)};\n`;
}

mkdirSync(distDir, { recursive: true });
writeFileSync(join(distDir, 'theme.css'), buildThemeCss());
writeFileSync(join(distDir, 'nativewind-preset.cjs'), buildNativewindPreset());
console.log(`design-tokens: wrote theme.css and nativewind-preset.cjs to ${distDir}`);
